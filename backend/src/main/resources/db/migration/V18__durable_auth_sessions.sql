ALTER TABLE members ADD COLUMN entity_version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_auth_sessions_member_id ON auth_sessions(member_id);
CREATE INDEX idx_auth_sessions_expires_at ON auth_sessions(expires_at);

ALTER TABLE refresh_tokens ADD COLUMN session_id BIGINT REFERENCES auth_sessions(id) ON DELETE CASCADE;
CREATE INDEX idx_refresh_tokens_session_id ON refresh_tokens(session_id);

